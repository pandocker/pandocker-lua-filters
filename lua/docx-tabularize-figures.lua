# docx-tabularize-figures.lua

Converts list of (inline) images to a subfigure table.
Co-work with pandoc-crossref filter (this must apply before crossref).
The Div must be figurediv class.
See also pandoc-crossref help page for subfigures: https://lierdakil.github.io/pandoc-crossref/#subfigures

## Syntax

:::{#fig:svg .figurediv col=2}

![another SVG file1](images/bitfield.svg){#fig:svg-1 width=73mm}
![another SVG file5](images/bitfield.svg){#fig:svg-5 width=73mm}
![another SVG file6](images/bitfield.svg){#fig:svg-6 width=73mm}

<Image caption>
:::

- col: number of subfigure columns. default is 1

